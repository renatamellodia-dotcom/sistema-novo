export function money(n) { return Number(n).toLocaleString('pt-BR',{style:'currency',currency:'BRL'}) }
export function today() { return new Date().toISOString().slice(0,10) }
export function uid() { return Math.random().toString(36).slice(2)+Date.now().toString(36) }
export function fmtDate(d) {
  if(!d) return ''
  const [y,m,day] = d.split('-')
  const months = ['jan.','fev.','mar.','abr.','mai.','jun.','jul.','ago.','set.','out.','nov.','dez.']
  return parseInt(day)+' de '+months[parseInt(m)-1]+' de '+y
}
export function fmtDateShort(d) {
  if(!d) return ''
  const [y,m,day] = d.split('-')
  return day+'/'+m+'/'+y
}
export function getLS(key, fallback) {
  if(typeof window==='undefined') return fallback
  try { const v=localStorage.getItem(key); return v?JSON.parse(v):fallback } catch { return fallback }
}
export function setLS(key, value) {
  if(typeof window!=='undefined') localStorage.setItem(key,JSON.stringify(value))
}
